import { readFile, writeFile } from "node:fs/promises";
import { defaultCopy } from "../packages/components/src/copy.ts";

const destination = new URL("../internal/platform/welcome_copy_generated.go", import.meta.url);
const text = `// Code generated by node scripts/welcome-copy.mjs; DO NOT EDIT.\n\npackage platform\n\nconst welcomeTitle = ${JSON.stringify(defaultCopy.home.welcome.title)}\nconst welcomeText = ${JSON.stringify(defaultCopy.home.welcome.text)}\n`;
const emailDestination = new URL("../internal/platform/email_copy_generated.go", import.meta.url);
const email = defaultCopy.emailNotifications;
const emailText = `// Code generated by node scripts/welcome-copy.mjs; DO NOT EDIT.\n\npackage platform\n\nconst emailSubject = ${JSON.stringify(email.subject)}\nconst emailSingle = ${JSON.stringify(email.single)}\nconst emailMultiple = ${JSON.stringify(email.multiple)}\nconst emailFooter = ${JSON.stringify(email.footer)}\n`;
for (const [file, content] of [[destination, text], [emailDestination, emailText]]) {
  if (process.argv.includes("--check")) {
    if ((await readFile(file, "utf8")) !== content) {
      throw new Error("Product copy is stale; run pnpm welcome-copy");
    }
  } else {
    await writeFile(file, content);
  }
}
