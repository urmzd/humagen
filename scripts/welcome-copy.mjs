import { readFile, writeFile } from "node:fs/promises";
import { defaultCopy } from "../packages/components/src/copy.ts";

const destination = new URL("../internal/platform/welcome_copy_generated.go", import.meta.url);
const text = `// Code generated by node scripts/welcome-copy.mjs; DO NOT EDIT.\n\npackage platform\n\nconst welcomeTitle = ${JSON.stringify(defaultCopy.home.welcome.title)}\nconst welcomeText = ${JSON.stringify(defaultCopy.home.welcome.text)}\n`;
if (process.argv.includes("--check")) {
  if ((await readFile(destination, "utf8")) !== text) {
    throw new Error("Welcome copy is stale; run pnpm welcome-copy");
  }
} else {
  await writeFile(destination, text);
}
